// extractText renders m to a PDF and returns its extracted plain text.
func extractText(t *testing.T, m report.Manifest) string {
	t.Helper()

	var buf bytes.Buffer
	require.NoError(t, report.Build(m, &buf))
	require.NotZero(t, buf.Len(), "Build produced an empty PDF")

	reader, err := pdf.NewReader(bytes.NewReader(buf.Bytes()), int64(buf.Len()))
	require.NoError(t, err, "generated bytes are not a valid PDF")
	require.GreaterOrEqual(t, reader.NumPage(), 1)

	textReader, err := reader.GetPlainText()
	require.NoError(t, err)

	text, err := io.ReadAll(textReader)
	require.NoError(t, err)

	return string(text)
}

// stripWhitespace makes substring checks independent of extractor spacing.
func stripWhitespace(s string) string {
	return strings.Join(strings.Fields(s), "")
}

func extractPages(t *testing.T, m report.Manifest) []string {
	t.Helper()

	var buf bytes.Buffer
	require.NoError(t, report.Build(m, &buf))

	reader, err := pdf.NewReader(bytes.NewReader(buf.Bytes()), int64(buf.Len()))
	require.NoError(t, err, "generated bytes are not a valid PDF")

	pages := make([]string, reader.NumPage())

	for n := 1; n <= reader.NumPage(); n++ {
		var sb strings.Builder
		for _, text := range reader.Page(n).Content().Text {
			sb.WriteString(text.S)
		}

		pages[n-1] = stripWhitespace(sb.String())
	}

	return pages
}

func pageContaining(pages []string, needle string) int {
	for index, page := range pages {
		if strings.Contains(page, needle) {
			return index
		}
	}

	return -1
}

// TestBuildKVLabelAndValueShareAPage sweeps the "Drive serial" row through every
// vertical offset to prove a kv label and value never land on different pages.
func TestBuildKVLabelAndValueShareAPage(t *testing.T) {
	t.Parallel()

	const (
		serial = "QRSERIAL9Z"
		label  = "Driveserial"
	)

	for fillers := 0; fillers <= 60; fillers++ {
		t.Run(fmt.Sprintf("fillers=%d", fillers), func(t *testing.T) {
			t.Parallel()

			manifest := completeManifest()
			manifest.Build.DriveSerial = serial

			files := make([]report.ArchiveFile, fillers)
			for index := range files {
				files[index] = report.ArchiveFile{
					Name:   fmt.Sprintf("filler-%03d.bin", index),
					Size:   int64(index + 1),
					SHA256: fmt.Sprintf("%064x", index),
				}
			}

			manifest.Archives[0].Files = files

			pages := extractPages(t, manifest)

			labelPage := pageContaining(pages, label)
			require.NotEqual(t, -1, labelPage, "the Drive serial label must render somewhere")

			assert.Contains(t, pages[labelPage], serial,
				"the Drive serial label and its value must render on the same page")
		})
	}
}

// TestBuildTableRowMonoCellStaysOnOnePage sweeps a disc row whose mono cell wraps
// further under Courier than Helvetica through every vertical offset, proving
// the row never splits across pages.
func TestBuildTableRowMonoCellStaysOnOnePage(t *testing.T) {
	t.Parallel()

	// Two lines under Courier 8.5 in a 46mm cell, but one under Helvetica.
	const device = "/dev/disk/by-id/il-1234567890"

	for fillers := 0; fillers <= 60; fillers++ {
		t.Run(fmt.Sprintf("fillers=%d", fillers), func(t *testing.T) {
			t.Parallel()

			manifest := completeManifest()
			manifest.Discs = []report.Disc{{Device: device}}

			files := make([]report.ArchiveFile, fillers)
			for index := range files {
				files[index] = report.ArchiveFile{
					Name:   fmt.Sprintf("filler-%03d.bin", index),
					Size:   int64(index + 1),
					SHA256: fmt.Sprintf("%064x", index),
				}
			}

			manifest.Archives[0].Files = files

			pages := extractPages(t, manifest)

			devicePage := pageContaining(pages, device)
			require.NotEqual(t, -1, devicePage,
				"the device path must render in full on one page, never split across a page break")

			assert.Contains(t, pages[devicePage], "burnedandverified",
				"the row's Notes cell must render on the same page as its device cell")
		})
	}
}

